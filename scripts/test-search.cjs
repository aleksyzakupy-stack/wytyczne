const fs=require('fs'),path=require('path'),assert=require('node:assert/strict');
const root=path.resolve(process.argv[2]||path.join(__dirname,'..'));
const modulePath=fs.existsSync(path.join(root,'skrypty/search_engine.js'))?'skrypty/search_engine.js':'src/search_engine.js';
const Search=require(path.join(root,modulePath)),data=JSON.parse(fs.readFileSync(path.join(root,'katalog.json'))),engine=Search.create(data);
const ids=q=>engine.search(q).map(x=>x.record.id);
const checks=[];
function test(query,include,exclude=[]){const found=ids(query);for(const id of include)assert(found.includes(id),`${query}: brak ${id}`);for(const id of exclude)assert(!found.includes(id),`${query}: błędny wynik ${id}`);checks.push({query,expected:include,excluded:exclude,result:'PASS',matches:found.length});}
